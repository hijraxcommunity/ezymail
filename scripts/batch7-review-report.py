def h2(text):
    return Paragraph(f'<b>{text}</b>', S['h2'])


def h3(text):
    return Paragraph(f'<b>{text}</b>', S['h3'])


def bullet(text):
    return Paragraph(text, S['bullet'], bulletText='-')


def make_table(header, rows, ratios, align_center_cols=()):
    col_w = [r * AVAIL for r in ratios]
    data = [[Paragraph(f'<b>{c}</b>', S['th']) for c in header]]
    for row in rows:
        cells = []
        for i, c in enumerate(row):
            style = S['tdc'] if i in align_center_cols else S['td']
            cells.append(Paragraph(str(c), style))
        data.append(cells)
    t = Table(data, colWidths=col_w, hAlign='CENTER', repeatRows=1)
    style_cmds = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        if i % 2 == 0:
            style_cmds.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_ODD))
    t.setStyle(TableStyle(style_cmds))
    return t


